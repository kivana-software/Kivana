const DICTS: Partial<Record<LanguageCode, Dict>> = {
  en: EN,
  es: ES,
  de: DE,
  fr: FR,
  it: IT,
  no: NO,
  pl: PL,
  pt: PT,
  nl: NL,
  sv: SV,
  da: DA,
  ru: RU,
  lt: LT,
}

export function t(language: LanguageCode | null | undefined, key: string, fallback?: string): string {
  const lang = (language ?? 'en') as LanguageCode
  const dict = DICTS[lang] ?? EN
  return dict[key] ?? EN[key] ?? fallback ?? key
}

export function tf(language: LanguageCode | null | undefined, key: string, params?: Record<string, string | number>, fallback?: string): string {
  let s = t(language, key, fallback)
  if (!params) return s
  for (const [k, v] of Object.entries(params)) {
    s = s.replaceAll(`{${k}}`, String(v))
  }
  return s
}

